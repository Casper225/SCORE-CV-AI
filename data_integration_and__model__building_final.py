class CVScoringEngine:
    """
    Calcule les 4 scores du modèle SCORE CV AI.

    1. TF-IDF     = 40%
    2. Entity     = 20%
    3. Skill      = 25%
    4. Relation   = 15%
    """

    TFIDF_WEIGHT = 0.40

    ENTITY_WEIGHT = 0.20

    SKILL_WEIGHT = 0.25

    RELATION_WEIGHT = 0.15

    def __init__(self):
        """
        Initialise le scoring engine.
        """

        logger.info(
            " CVScoringEngine initialized"
        )

        logger.info(
            f"Weights | "
            f"TF-IDF={self.TFIDF_WEIGHT} | "
            f"Entity={self.ENTITY_WEIGHT} | "
            f"Skill={self.SKILL_WEIGHT} | "
            f"Relation={self.RELATION_WEIGHT}"
        )

    @staticmethod
    def _normalize_score(
        score: float
    ) -> float:
        """
        Force un score entre 0 et 1.
        """

        try:

            score = float(score)

        except (
            ValueError,
            TypeError
        ):

            score = 0.0

        return round(
            float(
                np.clip(
                    score,
                    0.0,
                    1.0
                )
            ),
            3
        )

    # ========================================================
    # ENTITY SCORE
    # ========================================================

    def calculate_entity_score(
        self,
        entities: List[Dict[str, Any]],
        job_text: str
    ) -> float:

        if not entities or not job_text:

            return 0.0

        job_text_lower = (
            str(job_text).lower()
        )

        valid_entities = []

        for entity in entities:

            if not isinstance(
                entity,
                dict
            ):

                continue

            text = (
                entity.get("text")
                or ""
            )

            if text:

                valid_entities.append(
                    str(text).lower()
                )

        if not valid_entities:

            return 0.0

        matched = sum(

            1

            for entity_text
            in valid_entities

            if entity_text
            in job_text_lower
        )

        score = (
            matched
            /
            len(valid_entities)
        )

        score = self._normalize_score(
            score
        )

        logger.info(
            f"   Entity Score: {score:.3f}"
        )

        return score

    # ========================================================
    # SKILL SCORE
    # ========================================================

    def calculate_skill_score(
        self,
        skills: List[str],
        job_text: str
    ) -> float:

        if not skills or not job_text:

            return 0.0

        job_text_lower = (
            str(job_text).lower()
        )

        valid_skills = [

            str(skill).strip().lower()

            for skill in skills

            if skill
            and str(skill).strip()
        ]

        if not valid_skills:

            return 0.0

        matched = sum(

            1

            for skill
            in valid_skills

            if skill
            in job_text_lower
        )

        score = (
            matched
            /
            len(valid_skills)
        )

        score = self._normalize_score(
            score
        )

        logger.info(
            f"   Skill Score: {score:.3f}"
        )

        return score

    # ========================================================
    # RELATION SCORE
    # ========================================================

    def calculate_relation_score(
        self,
        relationships: List[Dict[str, Any]],
        job_text: str
    ) -> float:

        if not relationships or not job_text:

            return 0.0

        job_text_lower = (
            str(job_text).lower()
        )

        valid_relationships = [

            rel

            for rel in relationships

            if isinstance(
                rel,
                dict
            )
        ]

        if not valid_relationships:

            return 0.0

        matched = 0

        for relation in valid_relationships:

            source = str(
                relation.get(
                    "source",
                    ""
                )
            ).lower().strip()

            target = str(
                relation.get(
                    "target",
                    ""
                )
            ).lower().strip()

            source_match = (
                bool(source)
                and source
                in job_text_lower
            )

            target_match = (
                bool(target)
                and target
                in job_text_lower
            )

            if (
                source_match
                or target_match
            ):

                matched += 1

        score = (
            matched
            /
            len(valid_relationships)
        )

        score = self._normalize_score(
            score
        )

        logger.info(
            f"   Relation Score: {score:.3f}"
        )

        return score

    # ========================================================
    # FINAL SCORE
    # ========================================================

    def calculate_final_score(
        self,
        tfidf_score: float,
        entity_score: float,
        skill_score: float,
        relation_score: float
    ) -> float:

        tfidf_score = (
            self._normalize_score(
                tfidf_score
            )
        )

        entity_score = (
            self._normalize_score(
                entity_score
            )
        )

        skill_score = (
            self._normalize_score(
                skill_score
            )
        )

        relation_score = (
            self._normalize_score(
                relation_score
            )
        )

        final_score = (

            self.TFIDF_WEIGHT
            * tfidf_score

            +

            self.ENTITY_WEIGHT
            * entity_score

            +

            self.SKILL_WEIGHT
            * skill_score

            +

            self.RELATION_WEIGHT
            * relation_score
        )

        final_score = (
            self._normalize_score(
                final_score
            )
        )

        logger.info(
            f"   Final Score: "
            f"{final_score:.3f}"
        )

        return final_score

