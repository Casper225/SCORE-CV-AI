class ScoreCVAIModel:
    """
    Pipeline principal SCORE CV AI.
    """

    def __init__(
        self,
        top_k: int = 10,
        jsearch_api_key: Optional[str] = None
    ):

        logger.info(
            "\n"
            + "=" * 70
        )

        logger.info(
            "🚀 INITIALIZING SCORE CV AI"
        )

        logger.info(
            "=" * 70
        )

        self.integrator = (
            CVDataIntegrator()
        )

        self.matcher = (
            TfidfMatcher()
        )

        self.scorer = (
            CVScoringEngine()
        )

        self.jsearch = (
            JSearchClient(
                api_key=jsearch_api_key
            )
        )

        self.top_k = max(
            1,
            int(top_k)
        )

        logger.info(
            f" Pipeline initialized | "
            f"Top K = {self.top_k}"
        )

    # ========================================================
    # RUN PIPELINE
    # ========================================================

    def run(
        self,
        cleaned_text: str,
        entities: List[Dict[str, Any]],
        relationships: List[Dict[str, Any]],
        search_query: str,
        location: str = "Abidjan, Côte d'Ivoire",
        country: str = "ci",
        date_posted: Optional[str] = None
    ) -> Dict[str, Any]:

        logger.info(
            "\n"
            + "=" * 70
        )

        logger.info(
            " EXECUTING SCORE CV AI PIPELINE"
        )

        logger.info(
            "=" * 70
        )

        # ----------------------------------------------------
        # ÉTAPE 1 : DATA INTEGRATION
        # ----------------------------------------------------

        logger.info(
            "\n[ÉTAPE 1] Data Integration..."
        )

        profile = (
            self.integrator.integrate(
                cleaned_text,
                entities,
                relationships
            )
        )

        cv_matching_text = (
            self.integrator.build_matching_text(
                profile
            )
        )

        # ----------------------------------------------------
        # ÉTAPE 2 : JSEARCH API
        # ----------------------------------------------------

        logger.info(
            "\n[ÉTAPE 2] JSearch API..."
        )

        raw_jobs = (
            self.jsearch.search_jobs(

                query=search_query,

                location=location,

                page=1,

                num_pages=1,

                country=country,

                date_posted=date_posted
            )
        )

        jobs = (
            self.jsearch.simplify_jobs(
                raw_jobs
            )
        )

        if not jobs:

            logger.warning(
                " No jobs found."
            )

            return {

                "status":
                    "success",

                "message":
                    "No jobs found",

                "results":
                    [],

                "total_jobs_scored":
                    0
            }

        # ----------------------------------------------------
        # ÉTAPE 3 : MATCHING & SCORING
        # ----------------------------------------------------

        logger.info(
            f"\n[ÉTAPE 3] "
            f"Scoring {len(jobs)} jobs..."
        )

        ranked_jobs = []

        for index, job in enumerate(
            jobs,
            start=1
        ):

            logger.info(
                "\n"
                + "-" * 60
            )

            logger.info(
                f" JOB {index}/{len(jobs)}"
            )

            logger.info(
                f"Title: {job['title']}"
            )

            logger.info(
                f"Company: {job['company']}"
            )

            job_text = " ".join(

                [

                    str(
                        job.get(
                            "title",
                            ""
                        )
                    ),

                    str(
                        job.get(
                            "description",
                            ""
                        )
                    ),

                    str(
                        job.get(
                            "company",
                            ""
                        )
                    ),

                    str(
                        job.get(
                            "location",
                            ""
                        )
                    )
                ]
            )

            tfidf_score = (
                self.matcher.calculate_similarity(

                    cv_matching_text,

                    job_text
                )
            )

            entity_score = (
                self.scorer.calculate_entity_score(

                    entities,

                    job_text
                )
            )

            skill_score = (
                self.scorer.calculate_skill_score(

                    profile[
                        "skills"
                    ],

                    job_text
                )
            )

            relation_score = (
                self.scorer.calculate_relation_score(

                    relationships,

                    job_text
                )
            )

            final_score = (
                self.scorer.calculate_final_score(

                    tfidf_score,

                    entity_score,

                    skill_score,

                    relation_score
                )
            )

            ranked_jobs.append({

                "job":
                    job,

                "scores": {

                    "tfidf":
                        tfidf_score,

                    "entity":
                        entity_score,

                    "skill":
                        skill_score,

                    "relation":
                        relation_score,

                    "final":
                        final_score
                }
            })

        # ----------------------------------------------------
        # ÉTAPE 4 : RANKING
        # ----------------------------------------------------

        logger.info(
            "\n[ÉTAPE 4] Ranking jobs..."
        )

        ranked_jobs = sorted(

            ranked_jobs,

            key=lambda x:
                x["scores"]["final"],

            reverse=True
        )

        top_jobs = (
            ranked_jobs[
                :self.top_k
            ]
        )

        result = {

            "status":
                "success",

            "cv_id":
                "cv_001",

            "search_query":
                search_query,

            "location":
                location,

            "country":
                country,

            "total_jobs_scored":
                len(ranked_jobs),

            "top_k":
                self.top_k,

            "results":
                top_jobs,

            "timestamp":
                datetime.now().isoformat()
        }

        logger.info(
            "\n"
            + "=" * 70
        )

        logger.info(
            " SCORE CV AI PIPELINE COMPLETED"
        )

        logger.info(
            "=" * 70
        )

        return result


