class TfidfMatcher:
    """
    Calcule la similarité entre le CV et une offre
    grâce à TF-IDF + cosine similarity.

    TF-IDF :
        Term Frequency - Inverse Document Frequency

    Similarité :
        Cosine Similarity

    Score :
        0 = aucune similarité
        1 = similarité maximale
    """

    def __init__(self):
        """
        Initialise le vectorizer.
        """

        logger.info(
            " TfidfMatcher initialized"
        )

        # Correction : max_df=1.0 pour ne pas filtrer les mots
        # communs lorsque l'on compare 2 documents.
        self.vectorizer = TfidfVectorizer(

            max_features=5000,

            min_df=1,

            max_df=1.0,

            ngram_range=(1, 2),

            lowercase=True,

            sublinear_tf=True
        )

# ========================================================
    # CALCUL SIMILARITÉ
    # ========================================================

    def calculate_similarity(
        self,
        cv_text: str,
        job_text: str
    ) -> float:
        """
        Calcule la similarité cosinus TF-IDF.

        Args:
            cv_text:
                Texte du CV.

            job_text:
                Description du job.

        Returns:
            Score entre 0 et 1.
        """

        logger.info(
            " Calculating TF-IDF similarity..."
        )

        # ====================================================
        # SÉCURISATION
        # ====================================================

        if not cv_text or not job_text:

            logger.warning(
                " Empty text provided"
            )

            return 0.0

        try:

            # =================================================
            # VECTORISATION
            # ================================================

            vectors = self.vectorizer.fit_transform(
                [
                    str(cv_text),
                    str(job_text)
                ]
            )

            # =================================================
            # SIMILARITÉ COSINUS
            # =================================================

            similarity = cosine_similarity(
                vectors[0:1],
                vectors[1:2]
            )[0][0]

            score = float(
                np.clip(
                    similarity,
                    0.0,
                    1.0
                )
            )

            logger.info(
                f"TF-IDF Score: {score:.3f}"
            )

            return round(
                score,
                3
            )

        except Exception as e:

            logger.error(
                f" TF-IDF Error: {e}"
            )

            return 0.0

