class CVDataIntegrator:
    """
    Intègre le texte nettoyé, les entités NER et les relations
    dans un profil candidat structuré.

    RESPONSABILITÉS :

    - Stocker le texte nettoyé
    - Organiser les entités
    - Extraire les compétences
    - Conserver les relations
    - Construire le texte destiné au matching
    """

    def __init__(self):
        """Initialise l'intégrateur."""

        logger.info(" CVDataIntegrator initialized")

    def integrate(
        self,
        cleaned_text: str,
        entities: List[Dict[str, Any]],
        relationships: List[Dict[str, Any]]
    ) -> Dict[str, Any]:
        """
        Fusionne les données du CV dans un profil structuré.

        Args:
            cleaned_text:
                Texte nettoyé du CV.

            entities:
                Entités NER extraites du CV.

            relationships:
                Relations extraites du CV.

        Returns:
            Profil candidat structuré.
        """

        logger.info(" Integrating candidate data...")

        cleaned_text = cleaned_text or ""
        entities = entities or []
        relationships = relationships or []

        # ======================================================
        # EXTRACTION DES SKILLS
        # ======================================================

        skills = []

        for entity in entities:

                if not isinstance(entity, dict):
                    continue

                label = str(
                    entity.get("label", "")
                ).upper()

                text = (
                    entity.get("text")
                    or entity.get("target")
                    or ""
                )

                if label in ["SKILL", "CERTIFICATION"] and text:

                    skills.append(str(text).strip())

        # =================================================
        # DÉDUPLICATION DES SKILLS
        # ==================================================

        unique_skills = list(
            dict.fromkeys(
                skill
                for skill in skills
                if skill
            )
        )

        # ====================================================
        # GROUPEMENT DES ENTITÉS
        # ====================================================

        entities_by_type = {}

        for entity in entities:

            if not isinstance(entity, dict):
                continue

            entity_type = (
                entity.get("label")
                or "UNKNOWN"
            )

            entity_text = (
                entity.get("text")
                or ""
            )

            if entity_type not in entities_by_type:

                entities_by_type[entity_type] = []

            if entity_text:

                entities_by_type[entity_type].append(
                    entity_text
                )

        # =====================================================
        # PROFIL CANDIDAT
        # ====================================================

        profile = {

                    "text": cleaned_text,

                    "entities": entities,

                    "relationships": relationships,

                    "skills": unique_skills,

                    "entities_by_type": entities_by_type,

                    "num_entities": len(entities),

                    "num_skills": len(unique_skills),

                    "num_relationships": len(relationships)
                }

        logger.info(
                    f" Profile created | "
                    f"Entities: {profile['num_entities']} | "
                    f"Skills: {profile['num_skills']} | "
                    f"Relations: {profile['num_relationships']}"
                )

        return profile

    # ========================================================
    # CONSTRUCTION DU TEXTE DE MATCHING
    # ========================================================

    def build_matching_text(
            self,
            profile: Dict[str, Any]
        ) -> str:
            """
            Construit le texte utilisé pour le matching TF-IDF.

            Combine :

            - texte du CV
            - texte des entités
            - skills

            Returns:
                Texte complet de matching.
            """

            text = profile.get(
                "text",
                ""
            )

            entities = profile.get(
                "entities",
                []
            )

            skills = profile.get(
                "skills",
                []
            )

            # =====================================================
            # TEXTE DES ENTITÉS
            # =====================================================

            entity_texts = []

            for entity in entities:

                if not isinstance(entity, dict):
                    continue

                entity_text = (
                    entity.get("text")
                    or ""
                )

                if entity_text:

                    entity_texts.append(
                        str(entity_text)
                    )

            # ========================================================
            # COMBINAISON
            # ========================================================

            all_parts = [

                text,

                " ".join(entity_texts),

                " ".join(skills)

            ]

            matching_text = " ".join(
                part.strip()
                for part in all_parts
                if part
            )

            logger.info(
                f" Matching text built | "
                f"Length: {len(matching_text)} chars"
            )

            return matching_text.strip()

