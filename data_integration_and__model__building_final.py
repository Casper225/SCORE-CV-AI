def save_results_json(
    results: Dict[str, Any],
    filename: str = "score_cv_ai_results.json"
) -> str:

    try:

        with open(
            filename,
            "w",
            encoding="utf-8"
        ) as file:

            json.dump(

                results,

                file,

                indent=2,

                ensure_ascii=False,

                default=str
            )

        logger.info(
            f" JSON saved: {filename}"
        )

        return filename

    except Exception as e:

        logger.error(
            f"❌ JSON save error: {e}"
        )

        raise


