class JSearchClient:
    """
    Client réel JSearch via RapidAPI.

    RESPONSABILITÉS :

    - Authentification RapidAPI
    - Recherche d'offres réelles
    - Gestion des erreurs HTTP
    - Transformation des données JSearch
    - Préparation des offres pour SCORE CV AI
    """

    BASE_URL = (
        "https://jsearch-mega.p.rapidapi.com/search"
    )

    RAPIDAPI_HOST = (
        "jsearch-mega.p.rapidapi.com"
    )

    def __init__(
        self,
        api_key: Optional[str] = None,
        timeout: int = 20
    ):
        """
        Initialise le client JSearch.

        Priorité :

        1. api_key fournie directement
        2. variable d'environnement RAPIDAPI_KEY

        Args:
            api_key:
                Clé RapidAPI.

            timeout:
                Timeout HTTP en secondes.
        """

        # ----------------------------------------------------
        # RÉCUPÉRATION DE LA CLÉ
        # ----------------------------------------------------

        self.api_key = (
            api_key
            or os.getenv("RAPIDAPI_KEY")
        )

        self.timeout = timeout

        # ----------------------------------------------------
        # VALIDATION
        # ----------------------------------------------------

        if not self.api_key:

            raise ValueError(
                " RAPIDAPI_KEY introuvable.\n"
                "Configure ta clé RapidAPI avant "
                "d'utiliser JSearch."
            )

        # ----------------------------------------------------
        # HEADERS RAPIDAPI
        # ----------------------------------------------------

        self.headers = {

            "X-RapidAPI-Key":
                self.api_key,

            "X-RapidAPI-Host":
                self.RAPIDAPI_HOST
        }

        logger.info(
            " JSearchClient initialized"
        )

        logger.info(
            " RapidAPI authentication configured"
        )

    # ========================================================
    # SEARCH JOBS
    # ========================================================

    def search_jobs(
        self,
        query: str,
        location: str,
        page: int = 1,
        num_pages: int = 1,
        country: str = "ci",
        date_posted: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Recherche des offres réelles avec JSearch.
        """

        # ----------------------------------------------------
        # VALIDATION
        # ----------------------------------------------------

        if not query or not query.strip():

            raise ValueError(
                "query ne peut pas être vide."
            )

        if not location or not location.strip():

            raise ValueError(
                " location ne peut pas être vide."
            )

        logger.info(
            f" Searching JSearch | "
            f"Query='{query}' | "
            f"Location='{location}'"
        )

        # ----------------------------------------------------
        # PARAMÈTRES JSEARCH
        # ----------------------------------------------------

        params = {

            "query":
                f"{query} in {location}",

            "page":
                page,

            "num_pages":
                num_pages,

            "country":
                country
        }

        if date_posted:

            params["date_posted"] = (
                date_posted
            )

        try:

            response = requests.get(

                self.BASE_URL,

                headers=self.headers,

                params=params,

                timeout=self.timeout
            )

            logger.info(
                f" HTTP Status: "
                f"{response.status_code}"
            )

            if response.status_code == 401:

                logger.error(
                    "❌ 401 Unauthorized"
                )

                raise ValueError(
                    "Clé RapidAPI invalide "
                    "ou non autorisée."
                )

            if response.status_code == 403:

                logger.error(
                    "❌ 403 Forbidden"
                )

                raise PermissionError(
                    "Accès JSearch refusé. "
                    "Vérifie ton abonnement RapidAPI."
                )

            if response.status_code == 429:

                logger.error(
                    "❌ 429 Too Many Requests"
                )

                raise RuntimeError(
                    "Limite de requêtes RapidAPI dépassée."
                )

            response.raise_for_status()

            data = response.json()

            jobs = data.get(
                "data",
                []
            )

            if not isinstance(
                jobs,
                list
            ):

                logger.warning(
                    " Format JSearch inattendu."
                )

                return []

            logger.info(
                f" {len(jobs)} offres "
                f"récupérées depuis JSearch"
            )

            return jobs

        except requests.Timeout:

            logger.error(
                " Timeout JSearch."
            )

            raise RuntimeError(
                "Timeout lors de la connexion "
                "à JSearch."
            )

        except requests.ConnectionError:

            logger.error(
                "❌ Connection error JSearch."
            )

            raise RuntimeError(
                "Impossible de se connecter "
                "à JSearch."
            )

        except requests.RequestException as e:

            logger.error(
                f"❌ HTTP Error JSearch: {e}"
            )

            raise RuntimeError(
                f"Erreur API JSearch : {e}"
            )

        except (
            ValueError,
            PermissionError,
            RuntimeError
        ):

            raise

        except Exception as e:

            logger.exception(
                f"❌ Unexpected JSearch error: {e}"
            )

            raise RuntimeError(
                f"Erreur inattendue JSearch : {e}"
            )

    # ========================================================
    # SIMPLIFY JOBS
    # ========================================================

    def simplify_jobs(
        self,
        raw_jobs: List[Dict[str, Any]]
    ) -> List[Dict[str, Any]]:
        """
        Convertit les données JSearch vers
        le format SCORE CV AI.
        """

        logger.info(
            " Simplifying JSearch jobs..."
        )

        simplified = []

        for job in raw_jobs:

            if not isinstance(
                job,
                dict
            ):

                continue

            job_id = (
                job.get("job_id")
                or "unknown"
            )

            title = (
                job.get("job_title")
                or "No title"
            )

            company = (
                job.get("employer_name")
                or "Unknown"
            )

            description = (
                job.get("job_description")
                or ""
            )

            # Location avec fallback pour assurer la compatibilité JSearch
            location = (
                job.get("job_location")
                or job.get("job_city")
                or job.get("job_country")
                or ""
            )

            apply_link = (
                job.get("job_apply_link")
                or job.get("job_google_link")
                or ""
            )

            employment_type = (
                job.get("job_employment_type")
                or ""
            )

            remote = bool(
                job.get(
                    "job_is_remote",
                    False
                )
            )

            min_salary = job.get(
                "job_min_salary"
            )

            max_salary = job.get(
                "job_max_salary"
            )

            salary_period = job.get(
                "job_salary_period"
            )

            posted_at = (
                job.get("job_posted_at_datetime_utc")
                or ""
            )

            simplified.append({

                "job_id":
                    job_id,

                "title":
                    title,

                "description":
                    description,

                "company":
                    company,

                "location":
                    location,

                "apply_link":
                    apply_link,

                "employment_type":
                    employment_type,

                "remote":
                    remote,

                "min_salary":
                    min_salary,

                "max_salary":
                    max_salary,

                "salary_period":
                    salary_period,

                "posted_at":
                    posted_at
            })

        logger.info(
            f" {len(simplified)} jobs simplified"
        )

        return simplified

